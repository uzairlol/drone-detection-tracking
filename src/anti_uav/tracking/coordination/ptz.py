def build_absolute_move(
    pose: PtzPose,
    *,
    space: str = "Absolute",
    speed: float | None = None,
    token: str = "",
) -> str:
    """Build the ONVIF ``ContinuousMove`` XML for an absolute pose.

    Exposed as a pure function so the exact bytes that would go on the wire are
    inspectable in a test without a camera on the network. Pan/tilt are sent in
    normalised ``[-1, 1]`` units, which is what ONVIF Profile S expects - sending
    degrees here is a classic reason a PTZ silently refuses to move.
    """
    pan = float(_clamp(pose.yaw_deg / 180.0, -1.0, 1.0))
    tilt = float(_clamp(pose.pitch_deg / 90.0, -1.0, 1.0))
    zoom = float(max(pose.zoom - 1.0, 0.0))

    speed_element = ""
    if speed is not None:
        speed_element = f"<Speed x='{speed}' y='{speed}' z='{speed}'/>"

    return (
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<s:Envelope xmlns:s="http://www.w3.org/2003/05/soap-envelope"'
        ' xmlns:a="http://www.onvif.org/ver20/wsdl"'
        ' xmlns:tds="http://www.onvif.org/ver10/device/wsdl"'
        ' xmlns:ptz="http://www.onvif.org/ver20/ptz/wsdl">'
        f"<s:Header>{token}</s:Header>"
        "<s:Body>"
        "<ptz:ContinuousMove>"
        "<ptz:Position>"
        f"<ptz:PanTilt x='{pan:.6f}' y='{tilt:.6f}'/>"
        f"<ptz:Zoom x='{zoom:.6f}'/>"
        "</ptz:Position>"
        f"{speed_element}"
        f"</ptz:ContinuousMove>"
        "</s:Body>"
        "</s:Envelope>"
    )


def build_stop_move(token: str = "") -> str:
    """The ONVIF ``Stop`` request. Issued when a handoff is cancelled."""
    return (
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<s:Envelope xmlns:s="http://www.w3.org/2003/05/soap-envelope"'
        ' xmlns:ptz="http://www.onvif.org/ver20/ptz/wsdl">'
        f"<s:Header>{token}</s:Header>"
        "<s:Body><ptz:Stop/></s:Body>"
        "</s:Envelope>"
    )


def _describe_options(ptz: Any, pan_delta: float, tilt_delta: float, zoom_ratio: float) -> str:
    """A readable ONVIF options string, for the operator-facing log."""
    parts = ["Space=Absolute"]
    if pan_delta > 60:
        parts.append(f"pan=PRESET(fast, {ptz.max_pan_speed_deg_s:.0f} deg/s)")
    elif pan_delta > 5:
        parts.append("pan=VELOCITY(medium)")
    if tilt_delta > 20:
        parts.append("tilt=VELOCITY(medium)")
    if zoom_ratio > 4:
        parts.append("zoom=VELOCITY(slow)")
    parts.append(f"dwell={ptz.settle_time_s:.2f}s")
    return " ".join(parts)


def _clamp(value: float, low: float, high: float) -> float:
    return float(max(min(value, high), low))


def compose_pan_series(
    start_deg: float,
    target_deg: float,
    *,
    max_step_deg: float = 170.0,
) -> list[float]:
    """Break a pan across the ONVIF ``[-1, 1]`` limit into a safe path.

    A single ``ContinuousMove`` may not accept a full 360-degree delta, so a large
    rotation is split at the wrap point. The unwrap keeps the intermediate values
    on a continuous branch rather than spinning the long way round.
    """
    delta = normalize_angle(math.radians(target_deg - start_deg)) * 180.0 / math.pi
    if abs(delta) <= max_step_deg:
        return [target_deg]

    steps: list[float] = []
    remaining = delta
    while abs(remaining) > max_step_deg:
        step = math.copysign(max_step_deg, remaining)
        steps.append(unwrap_bearing(0.0, math.radians(step)) * 180.0 / math.pi + start_deg)
        start_deg = steps[-1]
        remaining -= step
    steps.append(target_deg)
    return steps


def recoverable(camera_id: str, coverage: Any) -> bool:
    """Whether a camera can accept a recovery pre-position command at all."""
    view = coverage.view(camera_id)
    return view is not None and view.is_ptz


def all_idle(controller: PtzController) -> bool:
    return not controller.busy_cameras()


def command_summary(controller: PtzController) -> Sequence[dict[str, Any]]:
    return [c.to_dict() for c in controller.commands[-20:]]
